function enhanceResult(){
  if(!t.won)return;
  const used=t.revealed;
  const wrong=Math.max(0,t.tries-1);
  $('#result').classList.remove('hidden');
  $('#resultTitle').textContent=`${used}개 단서 만에 정답!`;
  $('#resultText').innerHTML=`<b class="result-score">${t.score}점</b><span class="result-meta">정답 ${p.answer} · 오답 ${wrong}회 · 연속 ${s.stats.streak}일</span>`;
}
